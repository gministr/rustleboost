export function translate(lang: string, key: StringKey, vars?: Record<string, string | number>): string {
  let text: string = (lang === "en" ? en[key] : ru[key]) ?? ru[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  }
  return text;
}

export function useT() {
  const lang = useApp(s => s.settings.language);
  return (key: StringKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}
